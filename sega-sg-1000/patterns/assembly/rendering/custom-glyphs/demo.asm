    call glyph_out
    djnz colours
    ld hl,$1b00
    call glyph_address
    ld a,$d0
    call glyph_out
; Include, initialise and call: two screen cells share one installed picture.
example_install:
    ld hl,original_glyphs
    ld (G),hl
    ld a,1
    ld (G+2),a
    ld a,2
    ld (G+3),a
    call glyph_install
    ld a,1
    ld (G+4),a
    ld hl,66
    ld (G+5),hl
    call glyph_select
    ld hl,67
    ld (G+5),hl
    call glyph_select
; Diagnostic transport below is not required by a game.
    xor a
    ld (COMMAND),a
    ld a,239
    ld (COMMAND+1),a
mailbox:
    ld a,(COMMAND)
    or a
    jr z,mailbox
    cp 1
    jr nz,command_2
    call glyph_init
    jr complete
command_2:
    cp 2
    jr nz,command_3
    call glyph_install
    jr complete
command_3:
    cp 3
    jr nz,command_4
    call glyph_replace
    jr complete
command_4:
    cp 4
    jr nz,command_5
    call glyph_select
    jr complete
command_5:
    cp 5
    jr nz,complete
; Snapshot exactly 256 VRAM bytes into the private CPU buffer. Set read address,
; not write address; the VDP prefetches its first byte before the first IN.
    ld a,(G+11)
    ld c,a
    ld a,(DUMP_ADDRESS)
    call glyph_port
    ld a,(DUMP_ADDRESS+1)
    call glyph_port
    ld c,READ_PORT
    ld hl,BUFFER
    ld b,0
read_vram:
    in a,(c)
    ld (hl),a
    nop
    nop
    nop
    nop
    inc hl
    djnz read_vram
complete:
    xor a
    ld (COMMAND),a
    jr mailbox
