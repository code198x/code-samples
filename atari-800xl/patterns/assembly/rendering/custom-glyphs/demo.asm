    sta $4400,x
    sta $4ff0,x
    sta $53c0,x
    inx
    cpx #16
    bne guards
    jsr glyph_init
example_install:
    lda #<original_patterns
    sta G
    lda #>original_patterns
    sta G+1
    lda #1
    sta G+2
    lda #2
    sta G+3
    jsr glyph_install
    lda #1
    sta G+4
    lda #<82
    sta G+5
    lda #>82
    sta G+6
    jsr glyph_select
    inc G+5
    jsr glyph_select
; Diagnostic transport is optional: games call entries directly.
    lda #$22
    sta $d400
    lda #0
    sta COMMAND
    lda #239
    sta COMMAND+1
mailbox:
    lda COMMAND
    beq mailbox
    cmp #1
    bne next2
    jsr glyph_init
    jmp complete
next2:
    cmp #2
    bne next3
    jsr glyph_install
    jmp complete
next3:
    cmp #3
    bne next4
    jsr glyph_replace
    jmp complete
next4:
    cmp #4
    bne complete
    jsr glyph_select
complete:
    lda #0
    sta COMMAND
    jmp mailbox
interrupt:
    rti
kernel_start:
