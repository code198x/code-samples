    lda #<original_patterns
    sta G
    lda #>original_patterns
    sta G+1
    lda #1
    sta G+2
    lda #2
    sta G+3
    jsr glyph_install
    lda #1
    sta G+4
    lda #<82
    sta G+5
    lda #>82
    sta G+6
    jsr glyph_select
    inc G+5
    jsr glyph_select
; Diagnostic transport is optional; games call the routine directly.
    lda #0
    sta COMMAND
    lda #239
    sta COMMAND+1
mailbox:
    lda COMMAND
    beq mailbox
    cmp #1
    bne next_2
    jsr glyph_init
    jmp complete
next_2:
    cmp #2
    bne next_3
    jsr glyph_install
    jmp complete
next_3:
    cmp #3
    bne next_4
    jsr glyph_replace
    jmp complete
next_4:
    cmp #4
    bne next_5
    jsr glyph_select
    jmp complete
next_5:
    cmp #5
    bne complete
    ldx #0
read_colours:
    lda $d800,x
    and #15
    sta $0c00,x
    lda $d900,x
    and #15
    sta $0d00,x
    lda $da00,x
    and #15
    sta $0e00,x
    lda $db00,x
    and #15
    sta $0f00,x
    inx
    bne read_colours
complete:
    lda #0
    sta COMMAND
    jmp mailbox
kernel_start:
